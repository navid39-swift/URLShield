import json
from pathlib import Path

import pandas as pd

from host_features import extract_host, extract_host_features, tld_of

BASE_DIR = Path(__file__).resolve().parent

with open(BASE_DIR / "tld_rates.json") as f:
    tld = json.load(f)


def full_features(host):
    rate = tld["rates"].get(tld_of(host), tld["prior"])
    return [float(v) for v in extract_host_features(host)] + [float(rate)]


EDGE_CASES = [
    "https://www.Google.com/search?q=1",
    "http://user:pw@evil.com:8080/x",
    "paypal.com.secure-login.xyz/verify",
    "HTTP://WWW.Example.COM./",
    "http://[::1]:80/",
    "http://[::1",
    "https://evil.com\\@google.com",
    "192.168.0.1/login",
    "http://010.0.0.1/",
    "bit.ly/3xYz",
    "localhost",
    "bbc.co.uk",
    "  https://www.poste.it/track?id=9#top  ",
    "user@a@b.com",
    "https://xn--80ak6aa92e.com",
    "https://a..b.com",
    "",
]

df = pd.read_csv(BASE_DIR / "PhiUSIIL_Phishing_URL_Dataset.csv", usecols=["URL"])
urls = EDGE_CASES + df["URL"].sample(300, random_state=7).tolist()


def swift_literal(s):
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


lines = [
    "// Generated by make_parity_cases.py. Do not edit by hand.",
    "",
    "let hostParityCases: [(url: String, host: String, features: [Double])] = [",
]
for url in urls:
    host = extract_host(url)
    values = ", ".join(repr(v) for v in full_features(host))
    lines.append(f"    ({swift_literal(url)}, {swift_literal(host)}, [{values}]),")
lines.append("]")

out_path = BASE_DIR / "HostParityCases.swift"
out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("Wrote", len(urls), "cases to", out_path.name)